import type { Page } from "@playwright/test";
import type { ProbeSignals } from "./health";

const LOGIN_TEXT = [
  /log\s*in/i,
  /sign\s*in/i,
  /anmelden/i,
  /einloggen/i,
  /create.*account/i,
  /sign\s*up.*free/i,
  /welcome back/i,
  /continue with google/i,
  /continue with apple/i,
  /continue with microsoft/i,
  /forgot.?password/i,
];

const LOGIN_URL = [/\/login/i, /\/auth/i, /\/sign.?in/i, /accounts\.google/i];

export function brandPatterns(platform: string): RegExp[] {
  switch (platform) {
    case "ChatGPT":
      return [/chatgpt/i, /openai/i];
    case "Claude":
      return [/claude/i, /anthropic/i];
    case "DeepSeek":
      return [/deepseek/i, /deep\s*seek/i];
    case "Grok":
      return [/\bgrok\b/i, /\bx\.ai\b/i, /\bxai\b/i];
    case "Perplexity":
      return [/perplexity/i];
    case "Gemini":
      return [/gemini/i];
    default:
      return [];
  }
}

export function chatSelectors(platform: string): string[] {
  switch (platform) {
    case "ChatGPT":
      return [
        "div#prompt-textarea",
        'div.ProseMirror[contenteditable="true"]',
        'div[contenteditable="true"][role="textbox"]',
      ];
    case "Claude":
      return [
        '[data-testid="composer-input"]',
        'fieldset div[contenteditable="true"]',
        'div[contenteditable="true"]',
      ];
    case "Grok":
      return [
        'textarea[aria-label="Ask Grok anything"]',
        'textarea[placeholder="What do you want to know?"]',
        "textarea[placeholder]",
      ];
    case "Gemini":
      return [
        "rich-textarea",
        '.ql-editor[contenteditable="true"]',
        "div[contenteditable='true']",
      ];
    case "Perplexity":
      return [
        'div[role="textbox"][contenteditable="true"]',
        '.ProseMirror[contenteditable="true"]',
      ];
    case "DeepSeek":
      return ["textarea#chat-input", "#ds-chat-input", "textarea[placeholder]"];
    default:
      return [];
  }
}

export async function collectDiagnostics(page: Page): Promise<{
  final_url: string;
  page_title: string;
  body_snippet: string;
}> {
  let final_url = "";
  let page_title = "";
  let body_snippet = "";
  try {
    final_url = page.url();
  } catch {
    /* page already closed */
  }
  try {
    page_title = await page.title();
  } catch {
    /* ignore */
  }
  try {
    const text = await page.locator("body").innerText({ timeout: 3000 });
    body_snippet = text.replace(/\s+/g, " ").trim().substring(0, 400);
  } catch {
    /* ignore */
  }
  return { final_url, page_title, body_snippet };
}

export async function detectCloudflare(page: Page): Promise<boolean> {
  try {
    const title = await page.title();
    if (
      /just a moment|attention required|cloudflare|security check|one more step/i.test(
        title,
      )
    ) {
      return true;
    }

    const bodyText = await page.locator("body").innerText({ timeout: 3000 });
    const indicators = [
      /performing security verification/i,
      /verify you are human/i,
      /just a moment/i,
      /checking your browser/i,
      /cloudflare/i,
    ].filter((pattern) => pattern.test(bodyText));
    if (indicators.length >= 2) return true;
    if (indicators.length >= 1 && bodyText.trim().length < 80) return true;

    if (
      (await page.locator('iframe[src*="challenges.cloudflare.com"]').count()) >
      0
    ) {
      return true;
    }
    if ((await page.locator(".cf-turnstile, #cf-turnstile-container").count()) > 0) {
      return true;
    }
  } catch {
    /* ignore */
  }
  return false;
}

export async function detectWaf(page: Page): Promise<boolean> {
  try {
    const title = await page.title();
    const bodyText = await page.locator("body").innerText({ timeout: 3000 });
    const combined = `${title} ${bodyText}`;
    return (
      /request could not be satisfied|request blocked|403 ERROR|generated by cloudfront|access denied.*cloudfront|aws.*waf/i.test(
        combined,
      )
    );
  } catch {
    return false;
  }
}

export async function detectLoginWall(page: Page): Promise<boolean> {
  const url = page.url();
  if (LOGIN_URL.some((pattern) => pattern.test(url))) return true;

  try {
    if ((await page.locator('input[type="password"]').count()) > 0) return true;
  } catch {
    /* ignore */
  }

  try {
    const bodyText = await page.locator("body").innerText({ timeout: 4000 });
    const hits = LOGIN_TEXT.filter((pattern) => pattern.test(bodyText));
    if (hits.length >= 2) return true;
  } catch {
    /* ignore */
  }
  return false;
}

export async function detectBrand(page: Page, platform: string): Promise<boolean> {
  const patterns = brandPatterns(platform);
  try {
    const title = await page.title();
    if (patterns.some((pattern) => pattern.test(title))) return true;
    const bodyText = await page.locator("body").innerText({ timeout: 3000 });
    if (patterns.some((pattern) => pattern.test(bodyText))) return true;
  } catch {
    /* ignore */
  }
  return false;
}

export async function detectChat(page: Page, platform: string): Promise<boolean> {
  for (const selector of chatSelectors(platform)) {
    try {
      const visible = await page
        .locator(selector)
        .first()
        .isVisible({ timeout: 4000 });
      if (visible) return true;
    } catch {
      /* try the next selector */
    }
  }
  return false;
}

export async function inspectPage(
  page: Page,
  platform: string,
  url: string,
): Promise<{ signals: ProbeSignals; diagnostics: Awaited<ReturnType<typeof collectDiagnostics>>; httpStatus: number | null }> {
  let httpStatus: number | null = null;
  try {
    const response = await page.goto(url, {
      waitUntil: "domcontentloaded",
      timeout: 30000,
    });
    httpStatus = response ? response.status() : null;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return {
      httpStatus: null,
      diagnostics: await collectDiagnostics(page),
      signals: {
        httpStatus: null,
        navigationError: message.slice(0, 300),
        timeout: /timeout|timed out/i.test(message),
        cloudflare: false,
        waf: false,
        loginWall: false,
        brand: false,
        chatFound: false,
      },
    };
  }

  await page.waitForLoadState("networkidle", { timeout: 8000 }).catch(() => {});

  const cloudflare = await detectCloudflare(page);
  const waf = !cloudflare && (await detectWaf(page));
  const diagnostics = await collectDiagnostics(page);

  // Block pages are not content. Skip the slower selector scan.
  if (cloudflare || waf || (httpStatus !== null && httpStatus >= 500)) {
    return {
      httpStatus,
      diagnostics,
      signals: {
        httpStatus,
        navigationError: null,
        timeout: false,
        cloudflare,
        waf,
        loginWall: false,
        brand: false,
        chatFound: false,
      },
    };
  }

  const chatFound = await detectChat(page, platform);
  const loginWall = !chatFound && (await detectLoginWall(page));
  const brand = await detectBrand(page, platform);

  return {
    httpStatus,
    diagnostics,
    signals: {
      httpStatus,
      navigationError: null,
      timeout: false,
      cloudflare,
      waf,
      loginWall,
      brand,
      chatFound,
    },
  };
}
